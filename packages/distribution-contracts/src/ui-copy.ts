export function distributionText(
  locale: string | null | undefined,
  key: DistributionTextKey,
): string {
  const supported = DISTRIBUTION_UI_LOCALES.includes(locale as DistributionUiLocale)
    ? (locale as DistributionUiLocale)
    : "en";
  return DISTRIBUTION_UI_COPY[supported][key];
}

